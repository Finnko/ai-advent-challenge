export function abstainSupportAnswer(question: string): string {
  return [
    '### По документации',
    '',
    `В базе знаний Ozon нет ответа на вопрос «${question}».`,
    '',
    '### По вашему аккаунту и тикету',
    '',
    'Данных для ответа недостаточно.',
    '',
    '### Что делать',
    '',
    '1. Уточните вопрос или приложите номер тикета.',
    '2. Если вопрос срочный, напишите в поддержку Ozon через личный кабинет.',
  ].join('\n')
}

