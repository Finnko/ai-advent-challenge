export function buildJudgePrompt(
  task: Day3Task,
  answers: { id: StrategyId; content: string }[],
): string {
  const candidates = answers
    .map(({ id, content }) => `--- ${id} ---\n${content.trim()}`)
    .join('\n\n')

  return [
    `ЗАДАЧА:`,
    task.prompt,
    '',
    `ЭТАЛОННЫЙ ОТВЕТ:`,
    task.reference,
    '',
    `ОТВЕТЫ КАНДИДАТОВ:`,
    candidates,
  ].join('\n')
}
